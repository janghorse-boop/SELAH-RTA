package kr.joa.selahrta.ui.screens

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * **넓은 화면에서 계기를 얼마나 키우는가**(2026-10-01 담당자 지시).
 *
 * > SPL 화면은 세로가 맞는데 막대그래프가 너무 작아서 어울리지가 않습니다.
 *
 * 계기와 큰 숫자를 dp 로 못박아 두었더니, 폰에서 맞춘 크기가 태블릿
 * (753dp)에서는 **폭의 삼분의 일**밖에 안 됐다.
 *
 * ## 왜 시험을 따로 두는가
 *
 * 처음에는 **폭으로만** 셈했다. 그랬더니 태블릿을 눕혔을 때 배수가 3 이
 * 되어 계기가 세로를 다 먹었고, **「측정 시작」이 화면 밖으로 밀렸다** —
 * 기기에 깔아 보고서야 알았다. 담당자도 같은 것을 짚었다:
 *
 * > 현재 SPL 가로화면에서 측정 시작 버튼이 한 화면에 들어오는게 좋습니다.
 *
 * 셈이 화면 안에 묻혀 있으면 **기기를 꽂아야만** 확인할 수 있다. 떼어
 * 두면 여기서 숫자로 묻는다.
 *
 * ## 이 시험이 **못 보는 것**
 *
 * **단추가 실제로 한 화면에 드는지**는 안 본다 — 그것은 기기에서 봐야
 * 한다. 여기서 세우는 것은 **「좁은 쪽을 따른다」는 규칙**뿐이다.
 */
class MeterScaleTest {

    /** 폰은 **예전 그대로**다. 여기가 바뀌면 이미 맞춰 둔 화면이 흔들린다. */
    @Test
    fun `폰 세로는 키우지 않는다`() {
        // 갤럭시 S23: 384 × 790dp(표시줄 뺀 값).
        assertEquals(1f, meterScaleFor(384, 790), 0.001f)
    }

    /** 태블릿 세로는 **둘 다 넉넉해** 커진다. */
    @Test
    fun `태블릿 세로는 키운다`() {
        // 갤럭시탭 S8: 753 × 1205dp. 폭 1.88 · 높이 1.51 → 좁은 쪽 1.51.
        val s = meterScaleFor(753, 1205)
        assertTrue("$s", s > 1.4f && s < 1.6f)
    }

    /**
     * **눕히면 안 키운다.** 이것이 이번에 고친 자리다.
     *
     * 폭만 보면 3.01 이라 계기가 세로를 다 먹고 단추가 밀려난다.
     */
    @Test
    fun `태블릿 가로는 키우지 않는다`() {
        assertEquals(1f, meterScaleFor(1205, 753), 0.001f)
    }

    /** **좁은 쪽을 따른다**는 규칙 자체를 못박는다. */
    @Test
    fun `폭이 아무리 넓어도 높이가 모자라면 안 키운다`() {
        assertEquals(1f, meterScaleFor(4000, 700), 0.001f)
    }

    /**
     * **짐작으로 키우지 않는다.** 아주 큰 화면은 아직 본 적이 없어
     * 1.6 에서 멈춘다.
     */
    @Test
    fun `아주 큰 화면에서도 멈춘다`() {
        assertEquals(1.6f, meterScaleFor(4000, 4000), 0.001f)
    }

    /** **1 아래로는 안 내려간다.** 작은 화면에서 계기를 더 줄이면 못 읽는다. */
    @Test
    fun `작은 화면에서도 줄이지 않는다`() {
        assertEquals(1f, meterScaleFor(200, 300), 0.001f)
    }
}
