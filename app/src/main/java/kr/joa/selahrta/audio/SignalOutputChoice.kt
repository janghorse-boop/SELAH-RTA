package kr.joa.selahrta.audio

import kr.joa.selahrta.domain.MicKind

/**
 * **소리를 어디로 내보낼 것인가**(2026-09-30).
 *
 * ## 왜 고르는가
 *
 * USB 오디오 인터페이스를 꽂으면 안드로이드가 **출력도 그쪽으로** 보낸다.
 * 그런데 **같은 USB 카드로 동시에 넣고 빼면 입력이 완전한 디지털 무음이
 * 되는** 기기가 있다. 실기기에서 쟀다(SM-S918N + UMC404HD):
 *
 * ```
 * 출력 안 정함 → 실제 출력=UMC404HD, 입력 RMS=-240.0dBFS  (죽음)
 * 폰 스피커로  → 실제 출력=SM-S918N,  입력 RMS= -67.8dBFS  (삶)
 * ```
 *
 * 걸리는 곳은 교정 마법사 **2단계**(소리를 틀고 입력을 본다)와
 * **4단계**(핑크 노이즈로 기준→대상→기준)다. 거기서 입력이 무음이 되면
 * **아무것도 못 잰 채로 넘어간다.**
 *
 * ## 무엇을 모르는가
 *
 * **기기 하나로 본 것이다.** 다른 인터페이스도 그런지 모른다. 그래서
 * 「USB 면 무조건 폰 스피커」가 **맞는 기본값인지도 아직 모른다** —
 * 다만 **입력이 죽는 것보다는 낫다**고 보았다.
 */
object SignalOutputChoice {

    /**
     * 출력을 **폰 스피커로 돌려야 하는가.**
     *
     * **재는 쪽이 USB 일 때만** 그렇게 한다. 내장 마이크로 재면서
     * 인터페이스로 소리를 내보내는 것은 **흔하고 쓸모 있는 조합**이라
     * 건드리지 않는다 — PA 로 신호를 넣고 폰으로 방을 재는 경우다.
     *
     * @param capturingFrom 지금 재고 있는 입력의 종류. 안 열렸으면 null.
     */
    fun preferBuiltInSpeaker(capturingFrom: MicKind?): Boolean =
        capturingFrom == MicKind.Usb
}
