package kr.joa.selahrta.ui.nav

import kr.joa.selahrta.R

/**
 * 화면 위쪽 칩. 아래 탭 하나가 칩 몇 개를 거느린다.
 *
 * 설교·찬양은 **같은 계측 화면의 다른 권장 범위**이고, RTA·피드백은
 * 다른 화면이다. 그래서 칩 하나가 곧 「지금 무엇을 보고 있는가」가 된다.
 */
enum class ViewMode(val labelKo: String, val section: NavSection) {
    /**
     * 음압 계측(2026-09-24 담당자 지시로 설교·찬양을 여기 안으로 넣음).
     *
     * 예전에는 「설교」·「찬양」이 각각 칩이었다. 그런데 둘은 **같은 화면의
     * 다른 권장 범위**일 뿐이라, 칩 두 자리를 쓰면서도 화면은 하나였다.
     * 구간은 화면 안에서 고른다.
     */
    Spl("SPL", NavSection.Measure),

    /**
     * 예배 기록(컨셉 화면 7번).
     *
     * ## 아래 탭으로 되돌렸다 (2026-09-26 담당자 지시)
     *
     * 2026-09-24 에 아래 탭에서 위 칩으로 옮겼다 — 그때는 기록이 빈
     * 화면이라 탭 한 자리가 아까웠다. 지금은 기록이 **실제로 쌓인다**
     * (Phase 10 연결). 그리고 측정 구역에 칩이 둘뿐이라, 「SPL」 칩은
     * 늘 켜져 있는 채로 자리만 차지했다.
     *
     * 아래로 내리면 칩 줄이 통째로 사라지고 측정 화면이 그만큼 넓어진다.
     *
     * **마이크 없이도 열린다.** 지난 기록을 보는 데 마이크가 필요 없다.
     */
    History("기록", NavSection.History),

    /**
     * 31밴드 RTA — **피드백 후보도 여기서 함께 본다**(2026-09-24 담당자 지시).
     *
     * 예전에는 「피드백」이 옆 칩이었다. 그런데 「어느 대역이 솟았나」와
     * 「그게 하울링인가」는 한 가지 질문이라, 두 화면을 번갈아 보며 주파수를
     * 머리로 맞춰 봐야 했다. 지금은 차트 위에 후보를 표식으로 찍고 바로
     * 아래에 정확한 주파수를 적는다.
     *
     * **분석 구역은 가로로만 본다**(`LockLandscape`, 2026-09-25 담당자 지시).
     * 31밴드는 가로로 늘어선 그림이라 세로에서는 막대가 실오라기처럼 보인다.
     * 잠금은 화면이 아니라 **구역**에 걸려 있다(`SelahApp`) — 화면마다 걸면
     * RTA↔FR 을 오갈 때 폰이 한 번 섰다가 다시 눕는다.
     */
    Rta("RTA", NavSection.Analyze),

    /**
     * Spectrum — FFT 한 장을 **칸 그대로** 본다(2026-09-25 검토안 3장).
     *
     * ## 이름이 FFT 가 아닌 까닭
     *
     * 담당자는 「FFT 버튼」이라 했는데, 검토안이 그 자리를 정확히 짚었다:
     *
     * > FFT 는 주파수 성분을 계산하는 분석 방법(알고리즘)이고, Spectrum 은
     * > 그 계산 결과를 주파수별로 보여주는 표시 방식이다.
     *
     * 화면 이름은 **보는 것**이어야 한다. FFT 는 이 화면이 쓰는 셈이고,
     * 「RTA | FFT」로 나란히 두면 밴드 묶음과 계산법을 같은 층에 놓는 꼴이라
     * 나중에 Spectrogram 이 붙을 때 어디에 둘지가 없어진다.
     *
     * ## RTA 와 무엇이 다른가
     *
     * RTA 는 밴드로 묶어 **어느 대역이 큰가**를 보고(EQ 를 그 단위로 만진다),
     * Spectrum 은 묶지 않아 **그 안에서 정확히 몇 Hz 인가**를 본다. 2.5k
     * 밴드가 솟았다는 것까지는 RTA 가 말하고, 그게 2,713Hz 라는 것은 여기서
     * 나온다 — EQ 에서는 다른 자리다.
     */
    Spectrum("Spectrum", NavSection.Analyze),

    /**
     * Spectrogram — 시간(가로) × 주파수(세로) × 레벨(색).
     *
     * ## RTA·Spectrum 이 못 하는 것
     *
     * 둘 다 **지금 이 순간**의 그림이다. 그런데 하울링을 다룰 때 정작 묻는
     * 것은 「2.5kHz 가 **언제부터** 올라왔나」, 「끊겼나 이어졌나」다.
     * 지금은 후보 목록의 지속 시간 숫자로만 알 수 있는데, 숫자 하나는
     * 「언제」를 말하지 못한다.
     *
     * ## 세로축이 로그인 까닭
     *
     * 담당자가 보여 준 그림(PsySound3)은 선형 0~5kHz 였다. 그대로 하면
     * 목소리의 기본 주파수와 배음이 아래쪽 5분의 1에 눌린다 — 예배당에서
     * 볼 것이 대부분 거기다. RTA·Spectrum 도 로그라 셋의 주파수 축이 같아야
     * 화면을 옮길 때 눈이 자리를 다시 잡지 않는다.
     */
    Spectrogram("Spectrogram", NavSection.Analyze),

    /**
     * FR — 방·PA 의 **크기 응답**을 핑크 잡음으로 본다.
     *
     * RTA 와 같은 그림을 다르게 본다. RTA 는 **지금 얼마나 큰가**(순간,
     * 절대), FR 은 **모아 보면 어느 대역이 묻히는가**(평균, 0dB 기준 편차)다.
     *
     * ## 맨 오른쪽에 둔다 (2026-09-26 담당자 지시)
     *
     * 예전에는 RTA 바로 옆이었다. 그런데 앞의 셋(RTA·Spectrum·Spectrogram)은
     * **들어오는 소리를 그대로 흘려 보는** 화면이고, FR 만 **핑크 잡음을
     * 틀어 한 번 재고 끝나는** 화면이다. 성격이 다른 것이 사이에 끼어
     * 있으면, 흐르는 셋을 오가다 실수로 들어와 소리를 내게 된다.
     *
     * 셋을 붙여 놓고 FR 을 끝에 두면 **줄의 왼쪽이 흐르는 것, 오른쪽이
     * 재는 것**으로 읽힌다.
     *
     * **전달함수가 아니다.** 화면이 그 말을 맨 앞에 적는다 — 위상은 알 수
     * 없고, 잰 것은 소리원·방·마이크를 합친 결과다.
     *
     * 앞의 셋과 함께 **가로로만 본다**(2026-09-25 담당자 지시). 31밴드
     * 곡선은 여기서도 가로로 늘어선 그림이다.
     */
    Fr("FR", NavSection.Analyze),

    /**
     * 소리를 내보내는 것들 — 시험 신호, 앞으로 주파수 발생기·L/R 테스트.
     *
     * 설정이 아니라 도구다. 값을 바꿔 두는 일이 아니라 **하는 일**이기
     * 때문이다.
     */
    Signal("시험 신호", NavSection.Tools),

    /**
     * 악기 EQ 가이드(명세 §6).
     *
     * **도구로 옮겨 살려 둔다**(2026-09-24 담당자 지시: 「악기 EQ는 일단
     * 도구 안에 살려두겠습니다. 이후에 방향을 정해서 다시 수정하겠습니다」).
     *
     * 분석에 있던 것을 잠시 뺐다가 여기로 왔다. 자리는 이쪽이 더 맞는다 —
     * 지금 들어오는 소리를 **읽는** 화면이 아니라 표를 **찾아보는** 화면이고,
     * 도구에 있는 다른 것들과 같은 성격이다.
     *
     * **마이크 없이도 열린다.** 캡처를 쓰지 않으므로 권한이 없어도 제
     * 내용을 그대로 보여준다(명세 §1 원칙 2).
     */
    InstrumentEq("악기 EQ", NavSection.Tools),
}

/**
 * 이 칩이 캡처를 쓰는가. 쓰지 않으면 권한이 없어도 막지 않는다.
 *
 * 악기 EQ 는 표를 찾아보는 화면이고, 기록은 지난 값을 보는 화면이다.
 * 둘 다 지금 들어오는 소리와 무관하다.
 */
val ViewMode.needsCapture: Boolean
    get() = this != ViewMode.History && this != ViewMode.InstrumentEq

/**
 * 아래쪽 탭 다섯.
 *
 * ## 「기록」이 도구와 설정 사이로 돌아왔다 (2026-09-26 담당자 지시)
 *
 * 2026-09-24 에는 기록이 빈 화면이라 아래 탭 한 자리를 「도구」에
 * 내주고 위 칩으로 내려보냈다. 지금은 기록이 실제로 쌓이고(Phase 10),
 * 측정 구역에 칩이 둘뿐이라 「SPL」 칩이 늘 켜진 채 자리만 차지했다.
 *
 * 되돌리니 **측정 구역의 칩 줄이 통째로 사라진다**([hasModeChips] 가
 * 세어서 정하므로 저절로 그렇게 된다).
 *
 * ## 글자를 뗐다 (같은 지시)
 *
 * 「현재 아이콘 이미지면 충분할 것 같습니다」. 다섯 자리를 나눠 쓰면서
 * 글자까지 넣으면 좁은 폰에서 줄바꿈이 나고, 아이콘만으로도 어디로
 * 가는지 알 수 있다. **읽어 주는 쪽에는 `contentDescription` 으로 같은
 * 말이 간다** — 좁히는 것과 안 알리는 것은 다른 일이다.
 *
 * 측정·분석·도구는 위 칩과 짝을 이룬다 — 아래에서 「분석」을 누르면 위
 * 칩이 RTA 로 가고, 위에서 RTA 를 고르면 아래가 「분석」으로 켜진다.
 * 두 줄이 서로 다른 곳을 가리키면 지금 어디 있는지 알 수 없다.
 */
enum class NavSection(val labelKo: String, val iconRes: Int) {
    Measure("측정", R.drawable.ic_nav_measure),
    Analyze("분석", R.drawable.ic_nav_analyze),
    Tools("도구", R.drawable.ic_nav_tools),
    History("기록", R.drawable.ic_nav_history),
    Settings("설정", R.drawable.ic_nav_settings),
}

/**
 * 아래 탭을 눌렀을 때 어느 칩으로 갈지. 마지막에 보던 칩을 기억해 돌아간다.
 *
 * **칩이 보이는지와 무관하게 부른다.** 칩이 한 개뿐이라 안 보이는 구역도
 * 화면은 그 칩의 것으로 바뀌어야 한다 — 이 둘을 같은 조건으로 묶었다가,
 * 분석에 칩이 사라지자 탭은 「분석」인데 화면은 측정이 떠 있었다.
 */
fun NavSection.defaultMode(last: ViewMode): ViewMode = when (this) {
    NavSection.Measure -> if (last.section == NavSection.Measure) last else ViewMode.Spl
    NavSection.Analyze -> if (last.section == NavSection.Analyze) last else ViewMode.Rta
    NavSection.Tools -> if (last.section == NavSection.Tools) last else ViewMode.Signal
    NavSection.History -> ViewMode.History
    NavSection.Settings -> last
}

/**
 * 위 칩이 보이는 구역인지 — **고를 것이 둘 이상일 때만** 보인다.
 *
 * 고를 것이 하나인 고르개는 고르개가 아니다. 칩 한 개가 덩그러니 떠서
 * 자리만 차지하고, 눌러도 아무 일이 없어 고장처럼 보인다.
 *
 * **세어서 정한다.** 예전에는 구역 이름을 손으로 적어 두었는데, 칩이
 * 빠질 때(피드백·악기 EQ, 2026-09-24) 이 줄을 같이 고치는 것을 잊으면
 * 한 개짜리 고르개가 그대로 남는다. 세어 보면 잊을 수가 없다.
 */
val NavSection.hasModeChips: Boolean
    get() = !hasOwnModeSwitch && ViewMode.entries.count { it.section == this } > 1

/**
 * **이 구역은 고르개를 화면 안에서 그린다** — 위 칩을 쓰지 않는다
 * (2026-09-25 담당자 지시: 「RTA 창안에 RTA, FR 버튼은 없애주고 박스안에 …
 * 작게 만들어서」).
 *
 * 분석의 모드는 「차트가 무엇을 그리는가」라서, 고르개가 가리키는 것과 붙어
 * 있는 편이 읽힌다. RTA 는 차트 상자 안에, FR 은 맨 위 한 줄에 둔다. 위에
 * 따로 칩 줄을 쓰면 눕힌 화면에서 차트가 그만큼 줄어든다.
 *
 * **[hasModeChips] 가 이 값을 본다.** 두 곳에 따로 적었다가 한쪽만 고치면,
 * 위 칩과 화면 안 고르개가 같이 떠서 같은 것을 두 번 묻게 된다.
 *
 * 측정(SPL·기록)은 그대로 위 칩이다 — 그쪽은 서로 다른 화면이라 안에 넣을
 * 자리가 없다.
 */
val NavSection.hasOwnModeSwitch: Boolean
    get() = this == NavSection.Analyze
